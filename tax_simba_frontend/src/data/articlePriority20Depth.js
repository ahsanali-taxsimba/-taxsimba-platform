const escapeHtml = (value) => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
export function appendPracticalDepth(article, upgrade, updatedAt, markerName = "taxsimba-priority20-depth") {
  if (!upgrade) return {};
  const marker = `<!-- ${markerName} -->`;
  const existing = String(article.content || '');
  const content = existing.includes(marker) ? existing : existing + `
${marker}
<section class="article-worked-example" aria-label="Worked example">
<p class="premium-kicker">Put it into practice</p>
<h2>${escapeHtml(upgrade.exampleTitle)}</h2>
<p class="article-example-label">Illustrative scenario — not a customer case or personal tax calculation.</p>
${upgrade.example.map(p=>`<p>${escapeHtml(p)}</p>`).join('')}
</section>
<section class="article-decision" aria-label="Decision guide">
<h2>A decision guide for this situation</h2>
<div class="article-decision-scroll" role="region" aria-label="Decision table" tabindex="0">
<table><caption>What to check and how to act</caption><thead><tr><th scope="col">Check</th><th scope="col">Practical action</th></tr></thead>
<tbody>${upgrade.decisionRows.map(([check,action])=>`<tr><th scope="row">${escapeHtml(check)}</th><td>${escapeHtml(action)}</td></tr>`).join('')}</tbody></table></div>
</section>
<section class="article-follow-up" aria-label="Follow-up questions">
<h2>Two more questions you may have</h2>
${upgrade.questions.map(([q,a])=>`<h3>${escapeHtml(q)}</h3><p>${escapeHtml(a)}</p>`).join('')}
</section>
<section class="article-preparation" aria-label="Preparation worksheet">
<h2>Your preparation worksheet</h2><p>Use these prompts to prepare for a conversation with your accountant. No signup is needed to download the plain-text checklist.</p>
<ul>${upgrade.worksheetPrompts.map(p=>`<li>${escapeHtml(p)}</li>`).join('')}</ul>
<a class="article-worksheet-download" href="${upgrade.downloadHref}" download>Download the preparation checklist (.txt)</a>
<p class="article-example-label">Save completed notes securely. Keep passwords and security codes out of your notes.</p>
</section>`;
  return { content, contentUpdatedAt: updatedAt, priorityDepthVersion: 1, preparationDownload: upgrade.downloadHref,
    readingMinutes: Math.max(1,Math.ceil(content.replace(/<[^>]*>/g,' ').split(/\s+/).filter(Boolean).length/200)) };
}

export function appendPriority20Depth(article) {
  return appendPracticalDepth(article, priority20Upgrades[article?.slug], priority20UpdatedAt);
}
